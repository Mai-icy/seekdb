#!/usr/bin/env python3
"""Schema-only SQL frontend; stdout is a serialized Substrait plan.

This provisional compiler runs in its own process, using DuckDB 1.5.6 and the
community Substrait producer. Sirius's GPU runtime uses its upstream-pinned
DuckDB 2.0 consumer. No database file or seekdb row reaches this compiler.
Replace this executable with a seekdb-native plan translator without changing
the Arrow adapter. Install the extension once with INSTALL substrait FROM
community; queries only LOAD it and never download dependencies.
"""
import struct
import sys
import duckdb


def read_string():
    header = sys.stdin.buffer.read(4)
    if len(header) != 4:
        raise ValueError("Truncated compiler input")
    (size,) = struct.unpack("<I", header)
    if size > 16 * 1024**2:
        raise ValueError("Compiler input exceeds bound")
    value = sys.stdin.buffer.read(size)
    if len(value) != size:
        raise ValueError("Truncated compiler string")
    return value.decode()


def main():
    if duckdb.__version__ != "1.5.6":
        raise RuntimeError("Schema-only compiler requires duckdb==1.5.6")
    ddl, sql = read_string(), read_string()
    with duckdb.connect(":memory:") as connection:
        connection.execute("LOAD substrait")
        # seekdb's MySQL ordering places NULL before non-NULL for ASC and after
        # non-NULL for DESC. Serialize that choice into Substrait SortFields.
        connection.execute("SET default_null_order='NULLS_FIRST_ON_ASC_LAST_ON_DESC'")
        # Generated by adapter_backend from seekdb catalog metadata. The SELECT
        # is bound/optimized but never executed on these empty catalog tables.
        connection.execute(ddl)
        connection.execute(
            "SET disabled_optimizers='statistics_propagation,compressed_materialization,in_clause,materialized_cte,late_materialization,column_lifetime'"
        )
        statements = connection.extract_statements(sql)
        if len(statements) != 1 or statements[0].type != duckdb.StatementType.SELECT:
            raise ValueError("Exactly one SELECT is required")
        (plan,) = connection.execute(
            "CALL get_substrait(?, enable_optimizer=true)", [sql]
        ).fetchone()
        sys.stdout.buffer.write(plan)


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
